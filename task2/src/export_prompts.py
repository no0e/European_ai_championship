"""Writes PROMPTS.md: the exact text of every prompt we sent (scored endpoints and ref endpoints), for reproducibility.
Source of truth: the answer files shipped in data/ (one JSON line per answer, the prompt included).
    python3 src/export_prompts.py        (run from task2/)"""
import collections, json
from pathlib import Path
T = Path(__file__).resolve().parent.parent
PAID = [('answers_ep.jsonl', 'Short black-box collection (21/11 evening, max_tokens 4 to 48)'),
        ('answers_long_ep.jsonl', 'Long collection (22/11, 01:20 - 03:29, 256 tokens)'),
        ('answers_hi_ep.jsonl', 'High-entropy collection (22/11, 07:50 - 07:58, 256 tokens)')]
REF = [('reference_answers.jsonl', 'Reference answers provided by the organisers (official prompts)'),
       ('snapshot_answers_ref2.jsonl', 'Ref answers collected by the team')]
def block(f, title):
    rows = [json.loads(l) for l in open(T / 'data' / f, encoding='utf-8')]
    by = collections.OrderedDict()
    for r in rows:
        k = r.get('probe') or 'off' + str(r.get('id'))
        d = by.setdefault(k, {'prompt': r['prompt'], 'n': 0, 'eps': set(), 'mt': set()})
        d['n'] += 1; d['eps'].add(r['endpoint']); d['mt'].add(str(r.get('max_tokens', 256)))
    out = [f'## {title}', '', f'File: `data/{f}` ({len(rows)} answers, {len(by)} distinct prompts).', '',
           '| Probe | Answers | Endpoints | max_tokens | Exact prompt |', '|---|---|---|---|---|']
    for k, d in by.items():
        p = d['prompt'].replace('|', '\\|').replace('\n', '<br>')
        out.append(f"| `{k}` | {d['n']} | {len(d['eps'])} | {', '.join(sorted(d['mt'], key=int))} | {p} |")
    return out + ['']
L = ['# Task 2 - every prompt we sent (reproducibility)', '',
     'Generated by `python3 src/export_prompts.py` from the answer files in `data/`. Each request was one `user` message',
     '(no system message: the server refuses them), without `temperature` or `seed` (ignored by the server). The tables',
     'give the exact text; the answers are in the files cited, one JSON line per answer (`endpoint`, `probe`, `repeat`,',
     '`prompt`, `max_tokens`, `response`).', '',
     'The prompt of the high-entropy collection was chosen offline, without any request, by sampling the local checkpoints',
     '(`src/whitebox/design.py`): it maximised the entropy per answer and the base-versus-simulated-fp8 divergence.', '']
for f, t in PAID: L += block(f, t)
L += ['# Training endpoints (ref-01 to ref-09, free)', '']
for f, t in REF: L += block(f, t)
(T / 'PROMPTS.md').write_text('\n'.join(L), encoding='utf-8')
print('wrote PROMPTS.md,', len(L), 'lines')
